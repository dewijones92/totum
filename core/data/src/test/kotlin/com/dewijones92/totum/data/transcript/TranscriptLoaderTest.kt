package com.dewijones92.totum.data.transcript

import com.dewijones92.totum.common.HttpUrl
import com.dewijones92.totum.common.SubtitleFormat
import com.dewijones92.totum.common.SubtitleTrack
import com.dewijones92.totum.data.net.FetchResult
import com.dewijones92.totum.data.net.HttpTextFetcher
import kotlinx.coroutines.test.runTest
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class TranscriptLoaderTest {

    private val bodies = mutableMapOf<String, String>()
    private val fetched = mutableListOf<String>()
    private val fetcher = HttpTextFetcher { url ->
        fetched += url.value
        bodies[url.value]?.let { FetchResult.Success(it) } ?: FetchResult.Failure("404", 404)
    }
    private val loader = TranscriptLoader(fetcher)
    private val vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nhello\n"
    private val feedUrl = HttpUrl.of("https://example.com/feed.xml")

    private fun feed(transcript: String) = """
        <?xml version="1.0"?>
        <rss version="2.0"><channel><title>Show</title>
          <item><guid>ep-1</guid><title>Ep</title>$transcript</item>
        </channel></rss>
    """.trimIndent()

    @Test
    fun `a video reads its best caption track`() = runTest {
        val url = "https://www.youtube.com/api/timedtext?v=x&lang=en&fmt=vtt"
        bodies[url] = vtt
        val track = SubtitleTrack("en", "English", HttpUrl.of(url), autoGenerated = true, format = SubtitleFormat.VTT)

        val result = loader.forVideo("x", listOf(track), "en")

        assertEquals(listOf(Cue(1_000, 2_000, "hello")), (result as TranscriptResult.Loaded).cues)
        assertTrue(result.autoGenerated)
    }

    @Test
    fun `an episode reads the transcript its feed lists, and the feed is fetched once`() = runTest {
        bodies[feedUrl.value] = feed("""<podcast:transcript url="https://example.com/ep1.vtt" type="text/vtt"/>""")
        bodies["https://example.com/ep1.vtt"] = vtt

        assertTrue(loader.episodeAvailability("ep-1", feedUrl).available)
        val result = loader.forEpisode("ep-1", feedUrl)

        assertEquals("hello", (result as TranscriptResult.Loaded).cues.single().text)
        assertEquals(1, fetched.count { it == feedUrl.value })
    }

    @Test
    fun `an episode with no transcript, or only one it cannot read, says why`() = runTest {
        bodies[feedUrl.value] = feed("""<podcast:transcript url="https://example.com/ep1.html" type="text/html"/>""")

        assertEquals(false, loader.episodeAvailability("ep-1", feedUrl).available)
        assertTrue(loader.episodeAvailability("ep-1", feedUrl).why.contains("cannot read"))
        assertTrue(loader.forEpisode("ep-1", feedUrl) is TranscriptResult.None)
        assertTrue(loader.forEpisode("ep-2", feedUrl) is TranscriptResult.None)
    }
}
