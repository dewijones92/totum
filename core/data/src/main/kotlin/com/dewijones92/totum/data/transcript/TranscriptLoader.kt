package com.dewijones92.totum.data.transcript

import com.dewijones92.totum.common.Diag
import com.dewijones92.totum.common.HttpUrl
import com.dewijones92.totum.common.SubtitleFormat
import com.dewijones92.totum.common.SubtitleTrack
import com.dewijones92.totum.data.net.FetchResult
import com.dewijones92.totum.data.net.HttpTextFetcher
import com.dewijones92.totum.data.rss.ParsedTranscript
import com.dewijones92.totum.data.rss.RssParseResult
import com.dewijones92.totum.data.rss.RssParser
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.util.concurrent.ConcurrentHashMap

public sealed interface TranscriptResult {
    public data class Loaded(val cues: List<Cue>, val from: String, val autoGenerated: Boolean) : TranscriptResult
    public data class None(val why: String) : TranscriptResult
    public data class Failed(val why: String) : TranscriptResult
}

public data class TranscriptAvailability(val available: Boolean, val why: String)

public class TranscriptLoader(
    private val fetcher: HttpTextFetcher,
    private val now: () -> Long = System::currentTimeMillis,
) {
    private val feeds = ConcurrentHashMap<String, Pair<Long, Map<String, List<ParsedTranscript>>>>()
    private val loaded = ConcurrentHashMap<String, TranscriptResult.Loaded>()

    public fun forVideoAvailability(tracks: List<SubtitleTrack>, language: String): TranscriptAvailability =
        videoTrack(tracks, language)?.let { TranscriptAvailability(true, "captions: ${it.label}") }
            ?: TranscriptAvailability(false, "no captions in a format the transcript reads (${tracks.size} track(s))")

    public suspend fun forVideo(itemId: String, tracks: List<SubtitleTrack>, language: String): TranscriptResult {
        val track = videoTrack(tracks, language)
            ?: return TranscriptResult.None("no captions in a format the transcript reads (${tracks.size} track(s))")
        val format = if (track.format == SubtitleFormat.SRT) TranscriptFormat.SRT else TranscriptFormat.VTT
        return load(itemId, track.url, format, track.label, track.autoGenerated)
    }

    public suspend fun episodeAvailability(episodeId: String, feedUrl: HttpUrl): TranscriptAvailability {
        val links = transcriptsOf(feedUrl)
            ?: return TranscriptAvailability(false, "the feed ${feedUrl.value} could not be read")
        val listed = links[episodeId] ?: return TranscriptAvailability(false, "the episode is not in ${feedUrl.value}")
        return when {
            listed.isEmpty() -> TranscriptAvailability(false, NO_TRANSCRIPT)
            listed.none { TranscriptParser.formatOf(it.type, it.url) != null } ->
                TranscriptAvailability(false, "$UNREADABLE (${listed.joinToString { it.type ?: it.url }})")
            else -> TranscriptAvailability(true, "the feed lists ${listed.size} transcript(s)")
        }
    }

    public suspend fun forEpisode(episodeId: String, feedUrl: HttpUrl): TranscriptResult {
        val links = transcriptsOf(feedUrl) ?: return TranscriptResult.Failed("the feed could not be read")
        val listed = links[episodeId] ?: return TranscriptResult.None("the episode is no longer in its feed")
        val (link, format) = listed.mapNotNull { t ->
            TranscriptParser.formatOf(t.type, t.url)?.let { f -> HttpUrl.parse(t.url)?.let { it to f } }
        }.minByOrNull { (_, format) -> format.ordinal }
            ?: return TranscriptResult.None(if (listed.isEmpty()) NO_TRANSCRIPT else UNREADABLE)
        return load(episodeId, link, format, "the show's transcript", autoGenerated = false)
    }

    private fun videoTrack(tracks: List<SubtitleTrack>, language: String): SubtitleTrack? =
        pickTranscriptTrack(tracks.filter { it.format != SubtitleFormat.TTML }, language)

    private suspend fun load(
        itemId: String,
        url: HttpUrl,
        format: TranscriptFormat,
        from: String,
        autoGenerated: Boolean,
    ): TranscriptResult {
        loaded["$itemId|${url.value}"]?.let { return it }
        return when (val fetched = fetcher.fetch(url)) {
            is FetchResult.Failure -> TranscriptResult.Failed(fetched.detail).also {
                Diag.warn(TAG, "$itemId: transcript from $from could not be fetched: ${fetched.detail}")
            }
            is FetchResult.Success -> {
                val cues = withContext(Dispatchers.Default) {
                    TranscriptParser.parse(fetched.body, format, rolling = autoGenerated)
                }
                Diag.log(
                    TAG,
                    "$itemId: transcript from $from: ${cues.size} line(s) from ${fetched.body.length} chars of $format"
                )
                if (cues.isEmpty()) {
                    TranscriptResult.None("the transcript was empty")
                } else {
                    TranscriptResult.Loaded(cues, from, autoGenerated).also { result ->
                        if (loaded.size >= RESULTS_KEPT) loaded.clear()
                        loaded["$itemId|${url.value}"] = result
                    }
                }
            }
        }
    }

    private suspend fun transcriptsOf(feedUrl: HttpUrl): Map<String, List<ParsedTranscript>>? {
        feeds[feedUrl.value]?.let { (at, links) -> if (now() - at < FEED_KEPT_MS) return links }
        return when (val fetched = fetcher.fetch(feedUrl)) {
            is FetchResult.Failure -> null.also {
                Diag.warn(
                    TAG,
                    "feed ${feedUrl.value} for a transcript: ${fetched.detail}"
                )
            }
            is FetchResult.Success -> {
                val parsed = withContext(Dispatchers.Default) { RssParser().parse(fetched.body) }
                when (parsed) {
                    is RssParseResult.Success ->
                        parsed.feed.episodes
                            .mapNotNull { e -> (e.guid ?: e.enclosureUrl)?.let { it to e.transcripts } }
                            .toMap()
                            .also { links ->
                                if (feeds.size >= FEEDS_KEPT) feeds.clear()
                                feeds[feedUrl.value] = now() to links
                            }
                    is RssParseResult.Failure -> null.also {
                        Diag.warn(TAG, "feed ${feedUrl.value} for a transcript did not parse: ${parsed.detail}")
                    }
                }
            }
        }
    }

    private companion object {
        const val TAG = "transcript"
        const val FEED_KEPT_MS = 30 * 60_000L
        const val FEEDS_KEPT = 20
        const val RESULTS_KEPT = 10
        const val NO_TRANSCRIPT = "the feed lists no transcript"
        const val UNREADABLE = "the transcript is in a format it cannot read"
    }
}
