package com.dewijones92.totum.data.transcript

import com.dewijones92.totum.common.Diag
import com.dewijones92.totum.common.HttpUrl
import com.dewijones92.totum.common.SubtitleFormat
import com.dewijones92.totum.common.SubtitleTrack
import com.dewijones92.totum.data.net.FetchResult
import com.dewijones92.totum.data.net.HttpTextFetcher
import com.dewijones92.totum.data.rss.ParsedFeed
import com.dewijones92.totum.data.rss.RssParseResult
import com.dewijones92.totum.data.rss.RssParser
import java.util.concurrent.ConcurrentHashMap

public sealed interface TranscriptResult {
    public data class Loaded(val cues: List<Cue>, val from: String, val autoGenerated: Boolean) : TranscriptResult
    public data class None(val why: String) : TranscriptResult
    public data class Failed(val why: String) : TranscriptResult
}

public class TranscriptLoader(
    private val fetcher: HttpTextFetcher,
    private val now: () -> Long = System::currentTimeMillis,
) {
    private val feeds = ConcurrentHashMap<String, Pair<Long, ParsedFeed>>()

    public fun videoHasOne(tracks: List<SubtitleTrack>, language: String): Boolean =
        videoTrack(tracks, language) != null

    public suspend fun forVideo(tracks: List<SubtitleTrack>, language: String): TranscriptResult {
        val track = videoTrack(tracks, language)
            ?: return TranscriptResult.None("no captions in a format the transcript reads (${tracks.size} track(s))")
        val format = if (track.format == SubtitleFormat.SRT) TranscriptFormat.SRT else TranscriptFormat.VTT
        return load(
            track.url,
            format,
            "${track.label}${if (track.autoGenerated) " (auto-generated)" else ""}",
            track.autoGenerated
        )
    }

    public suspend fun forEpisode(episodeId: String, feedUrl: HttpUrl): TranscriptResult {
        val feed = feed(feedUrl) ?: return TranscriptResult.Failed("the feed could not be read")
        val episode = feed.episodes.firstOrNull { (it.guid ?: it.enclosureUrl) == episodeId }
            ?: return TranscriptResult.None("the episode is no longer in its feed")
        val (link, format) = episode.transcripts.firstNotNullOfOrNull { t ->
            TranscriptParser.formatOf(t.type, t.url)?.let { f -> HttpUrl.parse(t.url)?.let { it to f } }
        } ?: return TranscriptResult.None(
            if (episode.transcripts.isEmpty()) NO_TRANSCRIPT else UNREADABLE,
        )
        return load(link, format, "the show's transcript", autoGenerated = false)
    }

    public suspend fun episodeHasOne(episodeId: String, feedUrl: HttpUrl): Boolean =
        feed(feedUrl)?.episodes?.firstOrNull { (it.guid ?: it.enclosureUrl) == episodeId }
            ?.transcripts?.any { TranscriptParser.formatOf(it.type, it.url) != null } == true

    private fun videoTrack(tracks: List<SubtitleTrack>, language: String): SubtitleTrack? =
        pickTranscriptTrack(tracks.filter { it.format != SubtitleFormat.TTML }, language)

    private suspend fun load(
        url: HttpUrl,
        format: TranscriptFormat,
        from: String,
        autoGenerated: Boolean,
    ): TranscriptResult =
        when (val fetched = fetcher.fetch(url)) {
            is FetchResult.Failure -> TranscriptResult.Failed(fetched.detail).also {
                Diag.warn(TAG, "transcript from $from could not be fetched: ${fetched.detail}")
            }
            is FetchResult.Success -> {
                val cues = TranscriptParser.parse(fetched.body, format)
                Diag.log(
                    TAG,
                    "transcript from $from: ${cues.size} line(s) from ${fetched.body.length} chars of $format"
                )
                if (cues.isEmpty()) {
                    TranscriptResult.None(
                        "the transcript was empty"
                    )
                } else {
                    TranscriptResult.Loaded(cues, from, autoGenerated)
                }
            }
        }

    private suspend fun feed(feedUrl: HttpUrl): ParsedFeed? {
        feeds[feedUrl.value]?.let { (at, feed) -> if (now() - at < FEED_KEPT_MS) return feed }
        return when (val fetched = fetcher.fetch(feedUrl)) {
            is FetchResult.Failure -> null.also { Diag.warn(TAG, "feed for a transcript: ${fetched.detail}") }
            is FetchResult.Success -> when (val parsed = RssParser().parse(fetched.body)) {
                is RssParseResult.Success -> parsed.feed.also { feeds[feedUrl.value] = now() to it }
                is RssParseResult.Failure -> null.also { Diag.warn(TAG, "feed for a transcript did not parse") }
            }
        }
    }

    private companion object {
        const val TAG = "transcript"
        const val FEED_KEPT_MS = 30 * 60_000L
        const val NO_TRANSCRIPT = "the feed lists no transcript"
        const val UNREADABLE = "the transcript is in a format it cannot read"
    }
}
