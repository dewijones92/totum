package com.dewijones92.totum.playback

import com.dewijones92.totum.common.HttpUrl
import com.dewijones92.totum.common.SubtitleFormat
import com.dewijones92.totum.common.SubtitleTrack
import org.junit.Assert.assertEquals
import org.junit.Test

class SubtitleChoicesTest {

    private fun fetched(code: String, label: String) =
        SubtitleTrack(
            code,
            label,
            HttpUrl.of("https://example.com/$code.vtt"),
            autoGenerated = false,
            format = SubtitleFormat.VTT
        )

    @Test
    fun `a subtitle track inside the file is offered when nothing was fetched`() {
        val choices = subtitleChoices(emptyList(), listOf(TextTrackSeen(language = "en", label = null)))

        assertEquals(listOf(SubtitleChoice("en", "English (in the file)")), choices)
    }

    @Test
    fun `a fetched track is not offered twice when the player lists it too`() {
        val choices = subtitleChoices(
            listOf(fetched("en", "English")),
            listOf(TextTrackSeen("en", null), TextTrackSeen("fr", "Français SDH")),
        )

        assertEquals(listOf(SubtitleChoice("en", "English"), SubtitleChoice("fr", "Français SDH")), choices)
    }

    @Test
    fun `a track with no language is still offered, once`() {
        val choices = subtitleChoices(emptyList(), listOf(TextTrackSeen(null, null), TextTrackSeen("und", null)))

        assertEquals(listOf(SubtitleChoice(UNDETERMINED_LANGUAGE, "Subtitles (in the file)")), choices)
    }
}
