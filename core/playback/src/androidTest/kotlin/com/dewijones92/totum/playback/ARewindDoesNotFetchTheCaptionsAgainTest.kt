package com.dewijones92.totum.playback

import android.os.Handler
import android.os.Looper
import androidx.media3.common.Player
import androidx.media3.common.util.UnstableApi
import androidx.media3.exoplayer.ExoPlayer
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.dewijones92.totum.common.HttpUrl
import com.dewijones92.totum.common.SubtitleFormat
import com.dewijones92.totum.common.SubtitleTrack
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.util.concurrent.CountDownLatch
import java.util.concurrent.TimeUnit
import java.util.concurrent.atomic.AtomicReference

@UnstableApi
@RunWith(AndroidJUnit4::class)
class ARewindDoesNotFetchTheCaptionsAgainTest {

    private val main = Handler(Looper.getMainLooper())

    private fun <T> onMain(block: () -> T): T {
        val result = AtomicReference<T>()
        val done = CountDownLatch(1)
        main.post {
            result.set(block())
            done.countDown()
        }
        done.await(MAIN_WAIT_S, TimeUnit.SECONDS)
        return result.get()
    }

    @Test
    fun captionsWithNoLengthAreFetchedOnceThoughPlaybackIsRewound() {
        LoopbackHttp { LoopbackHttp.Reply("200 OK", wav()) }.use { media ->
            LoopbackHttp { LoopbackHttp.Reply("200 OK", TTML.toByteArray(), sayLength = false) }.use { captions ->
                val port = captions.url.substringAfter("127.0.0.1:").substringBefore('/')
                val captionUrl = "http://[::1]:$port/api/timedtext?v=rewind${System.nanoTime()}&lang=en&fmt=ttml"
                val player = onMain { start(media.url, captionUrl) }
                Thread.sleep(PLAY_MS)
                val before = captions.requestsAnswered
                for (target in listOf(BACK_TO_MS, FURTHER_BACK_MS)) {
                    onMain { player.seekTo(target) }
                    Thread.sleep(SETTLE_MS)
                }
                val state = onMain { "${player.playbackState} at ${player.currentPosition}ms" }
                onMain { player.release() }
                val after = captions.requestsAnswered
                android.util.Log.i(
                    "dewidebug",
                    "rewind-captions: fetched $after time(s), $before before the rewinds; $state"
                )

                assertTrue("the captions are fetched before the rewinds", before >= 1)
                assertEquals("and not again for either rewind", before, after)
            }
        }
    }

    private fun start(mediaUrl: String, captionUrl: String): ExoPlayer {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val track = SubtitleTrack("en", "English", HttpUrl.of(captionUrl), autoGenerated = false, SubtitleFormat.TTML)
        return ExoPlayer.Builder(context)
            .setMediaSourceFactory(playbackSources(context))
            .build()
            .apply {
                setMediaItem(
                    androidx.media3.common.MediaItem.Builder()
                        .setUri(mediaUrl)
                        .setSubtitleConfigurations(listOf(track.toSubtitleConfiguration()))
                        .build(),
                )
                trackSelectionParameters = trackSelectionParameters.buildUpon().setPreferredTextLanguage("en").build()
                prepare()
                play()
                check(playbackState != Player.STATE_IDLE)
            }
    }

    private fun wav(): ByteArray {
        val data = SAMPLE_RATE * CHANNELS * 2 * SECONDS
        return ByteBuffer.allocate(WAV_HEADER + data).order(ByteOrder.LITTLE_ENDIAN).apply {
            put("RIFF".toByteArray()).putInt(WAV_HEADER - 8 + data).put("WAVE".toByteArray())
            put("fmt ".toByteArray()).putInt(16).putShort(1).putShort(CHANNELS.toShort())
            putInt(SAMPLE_RATE).putInt(SAMPLE_RATE * CHANNELS * 2).putShort((CHANNELS * 2).toShort()).putShort(16)
            put("data".toByteArray()).putInt(data)
        }.array()
    }

    private companion object {
        const val SAMPLE_RATE = 44_100
        const val CHANNELS = 2
        const val SECONDS = 60
        const val WAV_HEADER = 44
        const val PLAY_MS = 8_000L
        const val SETTLE_MS = 3_000L
        const val BACK_TO_MS = 2_000L
        const val FURTHER_BACK_MS = 500L
        const val MAIN_WAIT_S = 5L
        const val TTML = """<?xml version="1.0" encoding="utf-8"?>
<tt xmlns="http://www.w3.org/ns/ttml"><body><div>
<p begin="00:00:00.000" end="00:00:20.000">The first line.</p>
<p begin="00:00:20.000" end="00:00:40.000">The second line.</p>
<p begin="00:00:40.000" end="00:01:00.000">The third line.</p>
</div></body></tt>"""
    }
}
